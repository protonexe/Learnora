const PDFGenerator = {
  generateProgressReport: (studentName, courses, quizzes, stats) => {
    const content = `
LEARNORA - Progress Report
==========================
Student: ${studentName}
Date: ${new Date().toLocaleDateString()}

ACADEMIC SUMMARY
----------------
Total Courses: ${courses.length}
Completed Courses: ${courses.filter(c => c.progress === 100).length}
In Progress: ${courses.filter(c => c.progress > 0 && c.progress < 100).length}

Quizzes Taken: ${quizzes.length}
Average Score: ${stats.averageScore || 'N/A'}%

COURSE PROGRESS
---------------
${courses.map(c => `${c.name}: ${c.progress}%`).join('\n')}

Generated by Learnora
    `;
    
    const blob = new Blob([content], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `progress-report-${studentName.replace(/\s+/g, '-')}.txt`;
    a.click();
    URL.revokeObjectURL(url);
  },

  generateReportCard: (studentName, grades, courses) => {
    const content = `
LEARNORA - Report Card
=======================
Student: ${studentName}
Date: ${new Date().toLocaleDateString()}

COURSES ENROLLED
----------------
${courses.map(c => `${c.name}: ${c.progress}% complete`).join('\n')}

GRADES
------
${grades.length > 0 ? grades.map(g => `${g.assignment}: ${g.grade}`).join('\n') : 'No grades recorded yet.'}

Generated by Learnora
    `;
    
    const blob = new Blob([content], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `report-card-${studentName.replace(/\s+/g, '-')}.txt`;
    a.click();
    URL.revokeObjectURL(url);
  },

  generateAttendanceReport: (studentName, attendance) => {
    const present = attendance.filter(a => a.status === 'present').length;
    const total = attendance.length;
    const percentage = total > 0 ? Math.round((present / total) * 100) : 0;
    
    const content = `
LEARNORA - Attendance Report
============================
Student: ${studentName}
Date: ${new Date().toLocaleDateString()}

ATTENDANCE SUMMARY
------------------
Total Days: ${total}
Present: ${present}
Absent: ${total - present}
Attendance Rate: ${percentage}%

DAILY RECORD
------------
${attendance.map(a => `${a.date}: ${a.status}`).join('\n')}

Generated by Learnora
    `;
    
    const blob = new Blob([content], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `attendance-${studentName.replace(/\s+/g, '-')}.txt`;
    a.click();
    URL.revokeObjectURL(url);
  }
};

window.PDFGenerator = PDFGenerator;
